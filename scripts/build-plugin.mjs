// Bundles src/plugin/main.ts (and the website code it imports) into one dependency-free
// file the Claude plugin ships: claude-plugin/scripts/port4lleo.mjs.
//
//   node scripts/build-plugin.mjs           write the bundle
//   node scripts/build-plugin.mjs --check   fail if the committed bundle is out of date
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = fileURLToPath(new URL("..", import.meta.url));
const outfile = `${root}claude-plugin/scripts/port4lleo.mjs`;

const result = await build({
  entryPoints: [`${root}src/plugin/main.ts`],
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node20",
  tsconfig: `${root}tsconfig.json`,
  legalComments: "eof",
  write: false,
  banner: {
    js: [
      "// GENERATED by scripts/build-plugin.mjs from src/plugin/ -- do not edit by hand.",
      "// PORT4LLEO (MIT) -- https://github.com/axxess-triaxis/port4lleo",
      'import { createRequire as __createRequire } from "node:module";',
      "const require = __createRequire(import.meta.url);",
    ].join("\n"),
  },
});

const code = result.outputFiles[0].text;
if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(outfile, "utf8");
  } catch {
    /* missing counts as stale */
  }
  if (current.replace(/\r\n/g, "\n") !== code) {
    console.error("claude-plugin/scripts/port4lleo.mjs is out of date. Run: node scripts/build-plugin.mjs");
    process.exit(1);
  }
  console.log("Plugin bundle is up to date.");
} else {
  writeFileSync(outfile, code);
  console.log(`Wrote ${outfile} (${(code.length / 1024).toFixed(0)} KB)`);
}
